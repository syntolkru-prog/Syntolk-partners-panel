const patterns: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
  [/^Hi\s+(.+)$/i, (m) => `Здравствуйте, ${m[1]}`],
  [/^(.+) approved, (.+) paid$/i, (m) => `${m[1]} подтверждено, ${m[2]} выплачено`],
  [/^(\d+)d$/i, (m) => `${m[1]} дн.`],
  [/^(.+) recurring on every event$/i, (m) => `${m[1]} регулярно за каждое событие`],
  [/^(.+) recurring on every invoice( for (\d+) months)?$/i, (m) => `${m[1]} регулярно за каждый счёт${m[3] ? ` в течение ${m[3]} мес.` : ''}`],
  [/^(.+) on first subscription$/i, (m) => `${m[1]} за первую подписку`],
  [/^(.+) — customers get (.+) off for (\d+) months$/i, (m) => `${m[1]} — клиенты получают скидку ${m[2]} на ${m[3]} мес.`],
  [/^(\d+) partners$/i, (m) => `${m[1]} ${Number(m[1]) === 1 ? 'партнёр' : 'партнёров'}`],
  [/^(\d+) clicks \((\d+)D\)$/i, (m) => `${m[1]} кликов (${m[2]} дн.)`],
  [/^(\d+) days$/i, (m) => `${m[1]} ${Number(m[1]) === 1 ? 'день' : 'дней'}`],
  [/^(\d+)% recurring$/i, (m) => `${m[1]}% регулярно`],
  [/^(\d+)d ago$/i, (m) => `${m[1]} дн. назад`],
  [/^(\d+)h ago$/i, (m) => `${m[1]} ч назад`],
  [/^(\d+)m ago$/i, (m) => `${m[1]} мин назад`],
  [/^≤ (\d+) days$/i, (m) => `≤ ${m[1]} дней`],
  [/^≥ (\d+) days$/i, (m) => `≥ ${m[1]} дней`],
];

export function ruText(value: string): string {
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  const trimmed = value.trim();
  let translated = exact[trimmed] ?? trimmed;
  if (!exact[trimmed]) {
    for (const [pattern, fn] of patterns) {
      const match = trimmed.match(pattern);
      if (match) {
        translated = fn(match);
        break;
      }
    }
  }
  return `${leading}${translated}${trailing}`;
}

export function ruStatus(status: string): string {
  return exact[status] ?? ruText(status);
}

let installed = false;

/** Install a lightweight DOM bridge for legacy pages that still contain English literals. */
export function installRussianUi(): void {
  if (installed || typeof document === 'undefined') return;
  installed = true;
  document.documentElement.lang = 'ru';

  const apply = (root: Node): void => {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes: Text[] = root.nodeType === Node.TEXT_NODE ? [root as Text] : [];
    let node: Node | null;
    while ((node = walker.nextNode())) nodes.push(node as Text);
    for (const textNode of nodes) {
      const parent = textNode.parentElement;
      if (!parent || ['SCRIPT', 'STYLE', 'PRE', 'CODE', 'TEXTAREA'].includes(parent.tagName)) continue;
      const translated = ruText(textNode.nodeValue ?? '');
      if (translated !== textNode.nodeValue) textNode.nodeValue = translated;
    }

    const elements = root instanceof Element
      ? [root, ...Array.from(root.querySelectorAll('*'))]
      : root instanceof Document || root instanceof DocumentFragment
        ? Array.from(root.querySelectorAll('*'))
        : [];
    for (const element of elements) {
      for (const attribute of ['aria-label', 'placeholder', 'title', 'alt']) {
        const current = element.getAttribute(attribute);
        if (!current) continue;
        const translated = ruText(current);
        if (translated !== current) element.setAttribute(attribute, translated);
      }
    }
  };

  apply(document.body);
  new MutationObserver((records) => records.forEach((record) => record.addedNodes.forEach(apply))).observe(document.body, {
    childList: true,
    subtree: true,
  });
}
